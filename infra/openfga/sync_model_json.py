"""Keep the packaged JSON form of the authorization model in sync with ``model.fga``.

``infra/openfga/model.fga`` is the source of truth. ``mowdeck-authz`` ships its JSON form
(``libs/mowdeck-authz/src/mowdeck_authz/model.json``), generated by the official OpenFGA CLI,
so Python code (``bootstrap_model()``, ``InMemoryAuthorizer``) needs no DSL parser.

    python infra/openfga/sync_model_json.py --write   # regenerate (uv run poe fga-json)
    python infra/openfga/sync_model_json.py --check   # fail if stale (CI)

Requires Docker; the CLI image is pinned below (``FGA_CLI_IMAGE`` overrides it, CI uses the
GHCR mirror of ``infra/images.txt``).
"""

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

CLI_IMAGE = os.environ.get("FGA_CLI_IMAGE") or "openfga/cli:v0.8.1"
HERE = Path(__file__).resolve().parent
PACKAGED = HERE.parents[1] / "libs" / "mowdeck-authz" / "src" / "mowdeck_authz" / "model.json"


def transform() -> str:
    """Return the model as pretty JSON, transformed by the official CLI."""
    result = subprocess.run(  # noqa: S603
        [  # noqa: S607
            "docker",
            "run",
            "--rm",
            "-v",
            f"{HERE}:/w:ro",
            "-w",
            "/w",
            CLI_IMAGE,
            "model",
            "transform",
            "--file",
            "model.fga",
            "--output-format",
            "json",
        ],
        capture_output=True,
        text=True,
        check=True,
    )
    return json.dumps(json.loads(result.stdout), indent=2, sort_keys=True) + "\n"


def main() -> int:
    """Entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the packaged JSON")
    mode.add_argument("--check", action="store_true", help="fail if the packaged JSON is stale")
    args = parser.parse_args()
    wanted = transform()
    if args.write:
        PACKAGED.write_text(wanted, encoding="utf-8", newline="\n")
        print(f"wrote {PACKAGED}")
        return 0
    current = PACKAGED.read_text(encoding="utf-8") if PACKAGED.exists() else ""
    if current != wanted:
        print(f"{PACKAGED} is stale; run: uv run poe fga-json", file=sys.stderr)
        return 1
    print("model.json is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
