MAX_TABLE_ROWS = 45
MAX_PHOTOS = 4


@dataclass(frozen=True, slots=True)
class PhotoData:
    """One image for the report."""

    taken_at: datetime
    data: bytes


@dataclass(frozen=True, slots=True)
class ReportData:
    """Everything the report shows."""

    mower_name: str
    mower_model: str | None
    mower_serial: str | None
    trigger: str
    started_at: datetime
    ended_at: datetime | None
    generated_at: datetime
    points: list[Point]
    photos: list[PhotoData]


def _latin(text: str) -> str:
    return text.encode("latin-1", "replace").decode("latin-1")


def _when(value: datetime) -> str:
    return value.strftime("%Y-%m-%d %H:%M:%S")


def _nice_step(span_m: float) -> float:
    """A round grid step (1, 2, 5 times a power of ten) giving about five lines per span."""
    raw = max(span_m / 5, 1e-6)
    magnitude = 10.0 ** math.floor(math.log10(raw))
    for factor in (1, 2, 5, 10):
        if raw <= factor * magnitude:
            return factor * magnitude
    return 10 * magnitude  # pragma: no cover - the loop always returns


def _local(points: list[Point]) -> list[tuple[float, float]]:
    """Metres east and north of the first point (equirectangular, fine for a garden or a town)."""
    lat0, lon0 = points[0][0], points[0][1]
    kx = 111_320.0 * math.cos(math.radians(lat0))
    return [((lon - lon0) * kx, (lat - lat0) * 110_540.0) for lat, lon, _ in points]


def _plot(pdf: FPDF, points: list[Point], x: float, y: float, w: float, h: float) -> None:
    """The track on a metre grid inside the box (x, y, w, h) in millimetres."""
    local = _local(points)
    xs, ys = [p[0] for p in local], [p[1] for p in local]
    span = max(max(xs) - min(xs), max(ys) - min(ys), 10.0)
    step = _nice_step(span)
    pad = step / 2
    x0, x1 = min(xs) - pad, max(xs) + pad
    y0, y1 = min(ys) - pad, max(ys) + pad
    scale = min(w / (x1 - x0), h / (y1 - y0))
    ox = x + (w - (x1 - x0) * scale) / 2
    oy = y + (h - (y1 - y0) * scale) / 2

    def px(mx: float) -> float:
        return float(ox + (mx - x0) * scale)

    def py(my: float) -> float:
        return float(oy + (y1 - my) * scale)

    pdf.set_draw_color(150, 150, 150)
    pdf.rect(x, y, w, h)
    pdf.set_draw_color(220, 220, 220)
    pdf.set_line_width(0.1)
    pdf.set_font("Helvetica", size=6)
    pdf.set_text_color(120, 120, 120)
    gx = math.ceil(x0 / step) * step
    while gx <= x1:
        pdf.line(px(gx), oy, px(gx), oy + (y1 - y0) * scale)
        pdf.text(px(gx) + 0.5, y + h - 1, f"{gx:g} m")
        gx += step
    gy = math.ceil(y0 / step) * step
    while gy <= y1:
        pdf.line(ox, py(gy), ox + (x1 - x0) * scale, py(gy))
        pdf.text(x + 1, py(gy) - 0.5, f"{gy:g} m")
        gy += step
    pdf.set_draw_color(20, 80, 160)
    pdf.set_line_width(0.5)
    for (ax, ay), (bx, by) in itertools.pairwise(local):
        pdf.line(px(ax), py(ay), px(bx), py(by))
    pdf.set_fill_color(30, 160, 60)
    pdf.circle(px(xs[0]) - 1.5, py(ys[0]) - 1.5, 3, style="F")
    pdf.set_fill_color(200, 40, 40)
    pdf.circle(px(xs[-1]) - 1.5, py(ys[-1]) - 1.5, 3, style="F")
    pdf.set_text_color(0, 0, 0)


def build_report(data: ReportData, lang: str = "en") -> bytes:
    """Render the report; ``lang`` is ``de`` or ``en`` (anything else is English)."""
    t = _TEXT["de" if lang.startswith("de") else "en"]
    pdf = FPDF(format="A4", unit="mm")
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.set_title(_latin(f"{t['title']} - {data.mower_name}"))
    pdf.set_creator("MowDeck")
    pdf.add_page()
    left = pdf.l_margin
    width = pdf.epw

    def heading(text: str) -> None:
        pdf.ln(3)
        pdf.set_font("Helvetica", "B", 12)
        pdf.cell(0, 7, _latin(text), new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", size=10)

    def row(label: str, value: str) -> None:
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(55, 6, _latin(label))
        pdf.set_font("Helvetica", size=10)
        pdf.multi_cell(0, 6, _latin(value), new_x="LMARGIN", new_y="NEXT")

    pdf.set_font("Helvetica", "B", 20)
    pdf.cell(0, 10, _latin(t["title"]), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", size=10)
    pdf.set_text_color(90, 90, 90)
    pdf.cell(0, 6, _latin(t["subtitle"]), new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(0, 0, 0)

    heading(t["mower"])
    row(t["name"], data.mower_name)
    row(t["model"], data.mower_model or t["unknown"])
    row(t["serial"], data.mower_serial or t["unknown"])

    heading(t["alarm"])
    row(t["alarm"], t.get(f"kind_{data.trigger}", data.trigger))
    row(t["alarm_time"], _when(data.started_at) + " UTC")
    row(t["tracking_end"], _when(data.ended_at) + " UTC" if data.ended_at else t["running"])
    row(t["positions"], str(len(data.points)))
    if data.points:
        lat, lon, at = data.points[-1]
        row(t["last_position"], f"{lat:.6f}, {lon:.6f} ({_when(at)} UTC)")

    heading(t["track"])
    if data.points:
        top = pdf.get_y() + 1
        _plot(pdf, data.points, left, top, width, 95)
        pdf.set_y(top + 97)
        pdf.set_font("Helvetica", size=8)
        pdf.set_text_color(90, 90, 90)
        pdf.multi_cell(0, 4, _latin(t["track_note"]), new_x="LMARGIN", new_y="NEXT")
        pdf.set_text_color(0, 0, 0)
    else:
        pdf.cell(0, 6, _latin(t["no_track"]), new_x="LMARGIN", new_y="NEXT")

    if data.points:
        heading(t["table"])
        shown = thin(data.points, MAX_TABLE_ROWS)
        every = max(1, round(len(data.points) / len(shown)))
        if len(shown) < len(data.points):
            pdf.set_font("Helvetica", size=8)
            note = t["table_note"].format(n=every, total=len(data.points))
            pdf.cell(0, 5, _latin(note), new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Courier", size=9)
        pdf.cell(55, 5, _latin(t["time"]))
        pdf.cell(40, 5, _latin(t["lat"]))
        pdf.cell(40, 5, _latin(t["lon"]), new_x="LMARGIN", new_y="NEXT")
        for lat, lon, at in shown:
            pdf.cell(55, 4.6, _when(at))
            pdf.cell(40, 4.6, f"{lat:.6f}")
            pdf.cell(40, 4.6, f"{lon:.6f}", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", size=10)

    heading(t["photos"])
    if data.photos:
        for photo in data.photos[:MAX_PHOTOS]:
            if pdf.get_y() > 200:
                pdf.add_page()
            pdf.set_font("Helvetica", size=8)
            pdf.cell(0, 4, _when(photo.taken_at) + " UTC", new_x="LMARGIN", new_y="NEXT")
            pdf.image(BytesIO(photo.data), x=left, w=min(120, width))
            pdf.ln(2)
    else:
        pdf.cell(0, 6, _latin(t["no_photos"]), new_x="LMARGIN", new_y="NEXT")

    if pdf.get_y() > 220:
        pdf.add_page()
    heading(t["owner"])
    pdf.set_draw_color(120, 120, 120)
    for label in t["owner_fields"]:
        pdf.set_font("Helvetica", size=9)
        pdf.cell(60, 9, _latin(label))
        y = pdf.get_y() + 7
        pdf.line(left + 60, y, left + width, y)
        pdf.ln(9)

    pdf.ln(4)
    pdf.set_font("Helvetica", size=7)
    pdf.set_text_color(90, 90, 90)
    pdf.multi_cell(
        0, 3.5, _latin(t["generated"].format(when=_when(data.generated_at))), new_x="LMARGIN"
    )
    return bytes(pdf.output())
