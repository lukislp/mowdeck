"""Render the HTTP API reference (Markdown) from the services' OpenAPI documents.

Usage (from the repository root)::

    uv run poe api-reference          # writes docs/reference/api/*.md
    uv run poe api-reference-check    # exit 1 when a committed page is stale

The source of truth are the OpenAPI documents in ``apps/web/openapi`` (``uv run poe openapi``
exports them from the services). Every service gets one page with its operations grouped by tag
(parameters, request body, responses) and its schemas as property tables; ``index.md`` lists the
services. The pages are plain Markdown: they build with MkDocs in strict mode without a plugin,
load nothing from a CDN, and read the same in the GitHub wiki mirror and on GitHub itself.

The output is deterministic (sorted where the documents are unordered, no timestamps), so the
check compares the committed pages with a fresh rendering, like the OpenAPI export.
"""

import argparse
import json
import re
import sys
import unicodedata
from collections.abc import Iterable, Sequence
from pathlib import Path
from typing import Any

OPENAPI_DIR = Path("apps/web/openapi")
OUT_DIR = Path("docs/reference/api")
SOURCE_URL = "https://github.com/lukislp/mowdeck/blob/main/apps/web/openapi"
METHODS = ("get", "post", "put", "patch", "delete")
OPERATIONS_SKIPPED = {"/.well-known/mowdeck-module"}
"""The module descriptor is for Identity and the web app shell, not for scripts."""

PURPOSE: dict[str, str] = {
    "billing": "Plans, checkout and the Stripe webhook (only with billing enabled).",
    "device-gateway": "Mower links of the installation (operator view).",
    "entitlements": "What the account's plan allows; usage and limits.",
    "fleet": "Mowers, sites, groups, linked cloud accounts, base stations and commands.",
    "identity": "Accounts, users, roles, sessions, API tokens and personal access tokens.",
    "notifications": "Inbox, rules, channels and push devices.",
    "planner": "Mowing patterns, spot paths and plans.",
    "realtime": "The WebSocket for live state and command results (protocol in the guide).",
    "scheduler": "Schedules, their runs, rain pause and the weather.",
    "telemetry": "Current state, history, positions, maps, health and reports.",
    "vision": "AI assisted recovery: proposals, approvals and the provider settings.",
}

EXTRA: dict[str, list[str]] = {
    "realtime": [
        "## WebSocket",
        "",
        "`GET /api/v1/realtime/ws` upgrades to a WebSocket (not part of the OpenAPI document). "
        'The first message authenticates with an access token (`{"type": "auth", '
        '"token": "..."}`), then `subscribe` names the mowers. Messages, close codes and '
        "limits: [ADR 0018](../../adr/0018-realtime-websocket-protocol.md) and the "
        "[realtime README](https://github.com/lukislp/mowdeck/blob/main/services/realtime/"
        "README.md); a complete client is in [Scripting MowDeck](../../guides/scripting.md).",
        "",
    ],
}
"""Hand-written additions for what an OpenAPI document cannot describe."""

HEADER = "<!-- Generated by tools/repo-checks/scripts/api_reference.py: do not edit. -->\n"


# --- Text helpers -----------------------------------------------------------------------------


def _slug(text: str) -> str:
    """The anchor Python-Markdown's ``toc`` extension gives a heading (its default slugify)."""
    value = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("ascii")
    value = re.sub(r"[^\w\s-]", "", value).strip().lower()
    return re.sub(r"[-\s]+", "-", value)


class Anchors:
    """Unique anchors in heading order, as ``toc`` makes them (``x``, ``x_1``, ``x_2``)."""

    def __init__(self) -> None:
        self.used: set[str] = set()

    def add(self, text: str) -> str:
        base = _slug(text)
        anchor, number = base, 0
        while anchor in self.used:
            number += 1
            anchor = f"{base}_{number}"
        self.used.add(anchor)
        return anchor


def _text(value: str | None) -> str:
    """Docstring text for Markdown: reStructuredText literals become code, lines are joined."""
    if not value:
        return ""
    value = re.sub(r"``([^`]+)``", r"`\1`", value)
    paragraphs = [" ".join(part.split()) for part in re.split(r"\n\s*\n", value.strip())]
    return "\n\n".join(p for p in paragraphs if p)


def _cell(value: str | None) -> str:
    """One table cell: a single line, pipes escaped."""
    return _text(value).replace("\n\n", "<br>").replace("|", "\\|")


def _ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


# --- Schema rendering -------------------------------------------------------------------------


class Renderer:
    """Renders one OpenAPI document."""

    def __init__(self, service: str, document: dict[str, Any]) -> None:
        self.service = service
        self.doc = document
        self.schemas: dict[str, Any] = document.get("components", {}).get("schemas", {})
        self.anchors = Anchors()
        self.schema_anchor: dict[str, str] = {}

    def type_of(self, schema: dict[str, Any] | None, depth: int = 0) -> str:
        """A short, readable type: ``string (uuid)``, ``array of [MowerOut](#mowerout)``."""
        if not schema:
            return "any"
        if depth > 4:
            return "object"
        if "$ref" in schema:
            name = _ref_name(schema["$ref"])
            anchor = self.schema_anchor.get(name)
            return f"[{name}](#{anchor})" if anchor else name
        if "const" in schema:
            return f"`{json.dumps(schema['const'])}`"
        if "enum" in schema:
            return " \\| ".join(f"`{json.dumps(v)}`" for v in schema["enum"])
        for key in ("anyOf", "oneOf"):
            if key in schema:
                options = [o for o in schema[key] if o.get("type") != "null"]
                nullable = len(options) != len(schema[key])
                text = " or ".join(self.type_of(o, depth + 1) for o in options) or "null"
                return f"{text} or null" if nullable else text
        if "allOf" in schema:
            return " and ".join(self.type_of(o, depth + 1) for o in schema["allOf"])
        kind = schema.get("type")
        if isinstance(kind, list):
            return " or ".join(str(k) for k in kind)
        if kind == "array":
            return f"array of {self.type_of(schema.get('items'), depth + 1)}"
        if kind == "object" and "properties" not in schema:
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                return f"map of {self.type_of(extra, depth + 1)}"
            return "object"
        if kind is None:
            return "any"
        fmt = schema.get("format")
        return f"{kind} ({fmt})" if fmt else str(kind)

    @staticmethod
    def constraints(schema: dict[str, Any]) -> list[str]:
        """Limits worth knowing when writing a request."""
        found = []
        for key, label in (
            ("minLength", "min length"),
            ("maxLength", "max length"),
            ("minimum", "min"),
            ("maximum", "max"),
            ("exclusiveMinimum", "greater than"),
            ("exclusiveMaximum", "less than"),
            ("minItems", "min items"),
            ("maxItems", "max items"),
        ):
            if key in schema:
                found.append(f"{label} {schema[key]}")
        if "pattern" in schema:
            found.append(f"pattern `{schema['pattern']}`")
        if "default" in schema and schema["default"] is not None:
            found.append(f"default `{json.dumps(schema['default'])}`")
        return found

    # --- Operations ---------------------------------------------------------------------------

    def operations(self) -> list[tuple[str, str, str, dict[str, Any]]]:
        """``(tag, method, path, operation)`` in tag order, then path, then method order."""
        found = []
        for path, item in self.doc.get("paths", {}).items():
            if path in OPERATIONS_SKIPPED:
                continue
            for method in METHODS:
                operation = item.get(method)
                if operation is None:
                    continue
                tag = (operation.get("tags") or [self.service])[0]
                found.append((tag, method, path, operation))
        return sorted(found, key=lambda o: (o[0], o[2], METHODS.index(o[1])))

    def parameter_rows(self, operation: dict[str, Any]) -> list[str]:
        rows = []
        for parameter in operation.get("parameters", []):
            schema = parameter.get("schema", {})
            notes = [_cell(parameter.get("description") or schema.get("description"))]
            notes += self.constraints(schema)
            rows.append(
                f"| `{parameter['name']}` | {parameter['in']} | {self.type_of(schema)} | "
                f"{'yes' if parameter.get('required') else 'no'} | "
                f"{'; '.join(n for n in notes if n)} |"
            )
        return rows

    def body_line(self, operation: dict[str, Any]) -> str | None:
        body = operation.get("requestBody")
        if not body:
            return None
        parts = []
        for media, content in sorted(body.get("content", {}).items()):
            parts.append(f"`{media}` {self.type_of(content.get('schema'))}")
        required = " (required)" if body.get("required") else ""
        return f"**Request body**{required}: " + ", ".join(parts)

    def response_rows(self, operation: dict[str, Any]) -> list[str]:
        rows = []
        for status, response in sorted(operation.get("responses", {}).items()):
            contents = response.get("content", {})
            kinds = [
                f"`{media}` {self.type_of(content.get('schema'))}"
                for media, content in sorted(contents.items())
            ]
            rows.append(
                f"| {status} | {_cell(response.get('description'))} | "
                f"{', '.join(kinds) or 'no body'} |"
            )
        return rows

    def schema_names(self) -> list[str]:
        """Schemas used by the rendered operations (and what they use), sorted by name."""
        wanted: set[str] = set()
        pending: list[str] = []
        for _, _, _, operation in self.operations():
            pending.extend(_refs(operation))
        while pending:
            name = pending.pop()
            if name in wanted or name not in self.schemas:
                continue
            wanted.add(name)
            pending.extend(_refs(self.schemas[name]))
        return sorted(wanted, key=str.lower)

    def render(self) -> str:
        lines = [HEADER]
        title = f"{self.service} API"
        self.anchors.add(title)
        lines += [f"# {title}", ""]
        purpose = PURPOSE.get(self.service)
        if purpose:
            lines += [purpose, ""]
        lines += [
            f"Base path `/api/v1/{self.service}` behind the gateway. Authentication, rate limits "
            "and the error format are the same for every service: see "
            "[Scripting MowDeck](../../guides/scripting.md). Rendered from "
            f"[`apps/web/openapi/{self.service}.json`]({SOURCE_URL}/{self.service}.json) "
            "(OpenAPI 3.1), which you can also load into any OpenAPI tool.",
            "",
        ]
        operations = self.operations()
        names = self.schema_names()

        # Reserve anchors in document order: tags and operations come first on the page.
        plan: list[tuple[str, list[tuple[str, str, dict[str, Any]]]]] = []
        for tag, method, path, operation in operations:
            if not plan or plan[-1][0] != tag:
                plan.append((tag, []))
            plan[-1][1].append((method, path, operation))
        self.anchors.add("Operations")
        for tag, entries in plan:
            self.anchors.add(tag)
            for method, path, _ in entries:
                self.anchors.add(f"{method.upper()} {path}")
        for line in EXTRA.get(self.service, []):
            if line.startswith("#"):
                self.anchors.add(line.lstrip("#").strip())
        if names:
            self.anchors.add("Schemas")
        for name in names:
            self.schema_anchor[name] = self.anchors.add(name)

        lines += ["## Operations", ""]
        if not operations:
            lines += ["This service has no HTTP operations for clients.", ""]
        for tag, entries in plan:
            lines += [f"### {tag}", ""]
            for method, path, operation in entries:
                lines += self.operation_lines(method, path, operation)
        lines += EXTRA.get(self.service, [])
        if names:
            lines += ["## Schemas", ""]
            for name in names:
                lines += self.schema_lines(name)
        return "\n".join(lines).rstrip() + "\n"

    def operation_lines(self, method: str, path: str, operation: dict[str, Any]) -> list[str]:
        lines = [f"#### {method.upper()} {path}", ""]
        summary = operation.get("summary")
        description = _text(operation.get("description"))
        if summary:
            lines += [f"**{summary}**", ""]
        if description:
            lines += [description, ""]
        if operation.get("deprecated"):
            lines += ["!!! warning", "    Deprecated.", ""]
        parameters = self.parameter_rows(operation)
        if parameters:
            lines += [
                "| Parameter | In | Type | Required | Notes |",
                "| --- | --- | --- | --- | --- |",
                *parameters,
                "",
            ]
        body = self.body_line(operation)
        if body:
            lines += [body, ""]
        responses = self.response_rows(operation)
        if responses:
            lines += [
                "| Status | Meaning | Body |",
                "| --- | --- | --- |",
                *responses,
                "",
            ]
        return lines

    def schema_lines(self, name: str) -> list[str]:
        schema = self.schemas[name]
        lines = [f"### {name}", ""]
        description = _text(schema.get("description"))
        if description:
            lines += [description, ""]
        properties: dict[str, Any] = schema.get("properties", {})
        if not properties:
            plain = {key: value for key, value in schema.items() if key != "title"}
            lines += [f"Type: {self.type_of(plain)}", ""]
            return lines
        required = set(schema.get("required", []))
        lines += ["| Field | Type | Required | Notes |", "| --- | --- | --- | --- |"]
        for field, spec in properties.items():
            notes = [_cell(spec.get("description")), *self.constraints(spec)]
            lines.append(
                f"| `{field}` | {self.type_of(spec)} | {'yes' if field in required else 'no'} | "
                f"{'; '.join(n for n in notes if n)} |"
            )
        lines.append("")
        return lines


def _refs(node: Any) -> Iterable[str]:
    """Every schema name a node refers to (recursively)."""
    if isinstance(node, dict):
        for key, value in node.items():
            if key == "$ref" and isinstance(value, str):
                yield _ref_name(value)
            else:
                yield from _refs(value)
    elif isinstance(node, list):
        for value in node:
            yield from _refs(value)


# --- Pages ------------------------------------------------------------------------------------


def _index(documents: dict[str, dict[str, Any]]) -> str:
    lines = [
        HEADER,
        "# API reference",
        "",
        "Every MowDeck service publishes an HTTP API under `/api/v1/<service>` on the same origin "
        "as the web app. The pages below are generated from the OpenAPI documents the services "
        "export, so they always match the code of this version. Start with "
        "[Scripting MowDeck](../../guides/scripting.md) for authentication with a personal "
        "access token, rate limits, the error format and examples in curl, Python and "
        "JavaScript.",
        "",
        "| Service | Base path | Operations | What it does |",
        "| --- | --- | --- | --- |",
    ]
    for service, document in documents.items():
        count = len(Renderer(service, document).operations())
        lines.append(
            f"| [{service}]({service}.md) | `/api/v1/{service}` | {count} | "
            f"{PURPOSE.get(service, '')} |"
        )
    lines += [
        "",
        "The raw OpenAPI 3.1 documents are in "
        f"[`apps/web/openapi`]({SOURCE_URL.rsplit('/', 1)[0]}/openapi): load them into "
        "Swagger UI, Redoc, Scalar, Insomnia, Bruno or a client generator of your choice.",
    ]
    return "\n".join(lines) + "\n"


def build(root: Path) -> dict[str, str]:
    """``{file name: Markdown}`` for every page."""
    documents = {
        path.stem: json.loads(path.read_text(encoding="utf-8"))
        for path in sorted((root / OPENAPI_DIR).glob("*.json"))
    }
    pages = {"index.md": _index(documents)}
    for service, document in documents.items():
        pages[f"{service}.md"] = Renderer(service, document).render()
    return pages


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else "")
    parser.add_argument("--check", action="store_true", help="exit 1 when a page is stale")
    parser.add_argument("--root", type=Path, default=Path.cwd())
    args = parser.parse_args(argv)
    root: Path = args.root
    pages = build(root)
    out = root / OUT_DIR
    if args.check:
        stale = [
            name
            for name, text in pages.items()
            if not (out / name).is_file() or (out / name).read_text(encoding="utf-8") != text
        ]
        extra = sorted(p.name for p in out.glob("*.md") if p.name not in pages)
        if stale or extra:
            print(
                f"{OUT_DIR} is stale ({', '.join(stale + extra)}): run `uv run poe api-reference`",
                file=sys.stderr,
            )
            return 1
        return 0
    out.mkdir(parents=True, exist_ok=True)
    for leftover in out.glob("*.md"):
        if leftover.name not in pages:
            leftover.unlink()
    for name, text in pages.items():
        (out / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(pages)} pages to {OUT_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
