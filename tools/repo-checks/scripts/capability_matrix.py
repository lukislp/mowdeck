"""The rows of every provider table, in order, with their labels."""


@dataclass(frozen=True)
class Provider:
    """One installed provider and what the page shows about it."""

    descriptor: ProviderDescriptor
    enabled_by_default: bool
    profiles: list[CapabilityProfile] | None
    """None: the provider declares no profiles."""
    lexicon: ErrorLexiconInfo | None


# --- Loading ----------------------------------------------------------------------------------


def _descriptor(create: Callable[[ProviderContext], CloudProviderPlugin]) -> ProviderDescriptor:
    """The descriptor of the plugin on its fake cloud (no network)."""
    plugin = create(ProviderContext(fake=True))
    try:
        return plugin.descriptor
    finally:
        asyncio.run(plugin.close())


def installed_providers() -> list[Provider]:
    """Every provider of the ``mowdeck.cloud_providers`` entry points, by display name."""
    lexicons = ErrorLexiconRegistry()
    found: list[Provider] = []
    for provider_id, spec in sorted(installed_specs().items()):
        lexicon = lexicons.provider(cloud_provider=provider_id)
        found.append(
            Provider(
                descriptor=_descriptor(spec.create),
                enabled_by_default=spec.enabled_by_default,
                profiles=list(spec.capability_profiles()) if spec.capability_profiles else None,
                lexicon=lexicon.lexicon.info() if lexicon is not None else None,
            )
        )
    return sorted(found, key=lambda p: p.descriptor.name.lower())


def problems(providers: Iterable[Provider]) -> list[str]:
    """Declarations the page cannot show honestly."""
    found: list[str] = []
    for provider in providers:
        descriptor = provider.descriptor
        for problem in check_profiles(provider.profiles or []):
            found.append(f"{descriptor.provider}: {problem}")
        for profile in provider.profiles or []:
            if profile.tested_on_hardware and not descriptor.tested_on_hardware:
                found.append(
                    f"{descriptor.provider}/{profile.family}: tested on hardware, but the "
                    "provider's descriptor says it is not"
                )
    return found


# --- Cells ------------------------------------------------------------------------------------


def _slug(text: str) -> str:
    """The anchor Python-Markdown's ``toc`` extension gives a heading (its default slugify)."""
    value = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("ascii")
    value = re.sub(r"[^\w\s-]", "", value).strip().lower()
    return re.sub(r"[-\s]+", "-", value)


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _range(values: tuple[float, float], unit: str) -> str:
    low, high = values
    return f"{low:g} {unit}" if low == high else f"{low:g} to {high:g} {unit}"


def _detail(key: str, caps: MowerCapabilities) -> str:
    """What a supported feature offers in detail (ranges, lists); empty for plain flags."""
    match key:
        case ProfileFeature.NATIVE_PATTERNS:
            return ", ".join(sorted(caps.native_patterns))
        case ProfileFeature.START_OPTIONS:
            options = caps.start_options
            parts = []
            if options.obstacle_detection:
                parts.append(f"obstacle detection ({len(options.obstacle_detection)} modes)")
            if options.obstacle_laps_range:
                parts.append(f"laps around no-go zones {_range(options.obstacle_laps_range, '')}")
            if options.orders:
                parts.append("path order")
            if options.start_progress_range_pct:
                parts.append("start progress")
            return ", ".join(p.strip() for p in parts)
        case ProfileFeature.START_PLANS:
            kinds: dict[str, int] = {}
            for plan in caps.start_plans:
                kinds[plan.kind.value] = kinds.get(plan.kind.value, 0) + 1
            return ", ".join(k if n == 1 else f"{k} ({n})" for k, n in kinds.items())
        case ProfileFeature.BLADE_HEIGHT if caps.blade_height_range_mm:
            return _range(caps.blade_height_range_mm, "mm")
        case ProfileFeature.PATH_SPACING if caps.path_spacing_range_mm:
            return _range(caps.path_spacing_range_mm, "mm")
        case ProfileFeature.MOWING_SPEED if caps.max_speed_mps:
            return _range((caps.min_speed_mps or 0, caps.max_speed_mps), "m/s")
        case ProfileFeature.DRIVE_SPEED_SETTING if caps.drive_speed_setting:
            setting = caps.drive_speed_setting
            return _range((setting.min_mps, setting.max_mps), "m/s")
        case ProfileFeature.CAMERA if caps.camera is not CameraAccess.NONE:
            return f"over the {caps.camera.value}" if caps.camera is CameraAccess.CLOUD else "local"
        case ProfileFeature.RTK:
            return ", ".join(s.value.replace("_", " ") for s in sorted(caps.rtk_sources))
        case ProfileFeature.MAINTENANCE:
            return ", ".join(a.replace("_", " ") for a in sorted(caps.maintenance))
        case _:
            return ""


def mark(profile: CapabilityProfile, key: str) -> str:
    """The cell of ``key`` for ``profile`` (see the legend)."""
    if key in profile.supported:
        detail = _detail(key, profile.capabilities)
        word = VARIES if key in profile.varies else YES
        return f"{word}: {detail}" if detail else word
    if key in profile.varies:
        return VARIES
    if key in profile.not_offered:
        return NOT_OFFERED
    return NOT_YET


# --- Page -------------------------------------------------------------------------------------


def _setting_label(key: str) -> str:
    return key.replace("_", " ").capitalize()


def _table(profiles: Sequence[CapabilityProfile], rows: Iterable[tuple[str, str]]) -> list[str]:
    head = "| | " + " | ".join(_cell(p.name) for p in profiles) + " |"
    lines = [head, "| --- |" + " --- |" * len(profiles)]
    for key, label in rows:
        cells = " | ".join(_cell(mark(p, key)) for p in profiles)
        lines.append(f"| {_cell(label)} | {cells} |")
    return lines


def _lexicon(info: ErrorLexiconInfo | None) -> str:
    if info is None:
        return "none"
    unverified = f", {info.unverified} unverified" if info.unverified else ""
    return f"{info.entries} codes ({', '.join(info.locales)}){unverified}"


def _transports(provider: Provider) -> str:
    keys = (
        ProfileFeature.TRANSPORT_CLOUD,
        ProfileFeature.TRANSPORT_BLE_BRIDGE,
        ProfileFeature.TRANSPORT_WIFI,
    )
    labels = dict(GROUPS[0][1])
    found = [labels[k] for k in keys if any(k in p.supported for p in provider.profiles or [])]
    return ", ".join(found) or "none"


def _tested(provider: Provider) -> str:
    if not provider.descriptor.tested_on_hardware:
        return "no"
    tested = [p.name for p in provider.profiles or [] if p.tested_on_hardware]
    return f"yes ({', '.join(tested)})" if tested else "yes"


def _overview(providers: Sequence[Provider]) -> list[str]:
    lines = [
        "| Provider | Model families | Connection | Error lexicon | Tested on real hardware "
        "| On by default |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for provider in providers:
        descriptor = provider.descriptor
        families = (
            ", ".join(p.name for p in provider.profiles) if provider.profiles else "none declared"
        )
        lines.append(
            f"| [{_cell(descriptor.name)}](#{_slug(descriptor.name)}) | {_cell(families)} | "
            f"{_transports(provider)} | {_lexicon(provider.lexicon)} | {_tested(provider)} | "
            f"{'yes' if provider.enabled_by_default else 'no'} |"
        )
    return lines


def _provider_section(provider: Provider) -> list[str]:
    descriptor = provider.descriptor
    lines = [f"## {descriptor.name}", ""]
    summary = text_for(descriptor.summary, "en")
    if summary:
        lines += [summary, ""]
    facts = [
        f"provider id `{descriptor.provider}`",
        f"error lexicon: {_lexicon(provider.lexicon)}",
        "on by default" if provider.enabled_by_default else "off by default (operators enable it)",
    ]
    if descriptor.needs_developer_account:
        facts.append("needs a developer account at the vendor")
    lines += ["- " + fact for fact in facts]
    lines.append("")
    if not descriptor.tested_on_hardware:
        lines += [
            '!!! note "Not tested on real hardware"',
            "    Built and tested against recorded vendor data and a fake cloud only.",
            "",
        ]
    for warning in descriptor.warnings:
        lines += ["!!! warning", f"    {_cell(text_for(warning, 'en') or '')}", ""]
    profiles = provider.profiles
    if not profiles:
        lines += ["This provider declares no capability profiles yet.", ""]
        return lines
    lines += [
        "| Model family | Device models | Tested on real hardware |",
        "| --- | --- | --- |",
    ]
    for profile in profiles:
        models = ", ".join(f"`{m}`" for m in profile.models) or "none"
        lines.append(
            f"| {_cell(profile.name)} | {models} | "
            f"{'yes' if profile.tested_on_hardware else 'no'} |"
        )
    lines += ["", "### Commands", ""]
    lines += _table(profiles, [])[:2]
    lines.append(f"| {BASIC_COMMANDS} |" + f" {YES} |" * len(profiles))
    for group, rows in GROUPS:
        lines += ["", f"### {group}", ""]
        lines += _table(profiles, [(str(key), label) for key, label in rows])
    settings = sorted(
        key
        for key in SETTING_KEYS
        if any(key in p.supported or key in p.varies or key in p.not_offered for p in profiles)
    )
    lines += ["", "### Device settings", ""]
    if settings:
        lines += _table(profiles, [(key, _setting_label(key)) for key in settings])
        lines += ["", "Settings no family of this provider has are not listed."]
    else:
        lines.append("No family of this provider declares device settings.")
    lines += _notes(profiles)
    return lines


def _notes(profiles: Sequence[CapabilityProfile]) -> list[str]:
    """The families' notes in English; notes every family shares are listed once."""
    texts = [[_cell(text_for(note, "en") or "") for note in p.notes] for p in profiles]
    shared = [t for t in texts[0] if all(t in other for other in texts[1:])] if texts else []
    own = [
        (profile, [t for t in notes if t not in shared])
        for profile, notes in zip(profiles, texts, strict=True)
    ]
    if not shared and not any(t for _, t in own):
        return []
    lines = ["", "### Notes", ""]
    if shared:
        lines += [f"- {t}" for t in shared]
        lines.append("")
    for profile, notes in own:
        if notes:
            lines += [f"**{_cell(profile.name)}**", ""]
            lines += [f"- {t}" for t in notes]
            lines.append("")
    return lines


def render(providers: Sequence[Provider]) -> str:
    """The page."""
    lines = [
        HEADER,
        "# Capability matrix",
        "",
        "What MowDeck can do with the mowers of each provider, per model family. The page is "
        "generated from the adapters' code ([ADR 0071](../adr/0071-capability-matrix.md)): "
        "every provider declares a capability profile per model family, whose capabilities "
        "its own capability code computes for a representative mower, so the matrix changes "
        "with the code and is never edited by hand. A connected mower shows its exact "
        "capabilities on its own page; they can be narrower than its family's (an older "
        "firmware, a missing module, a link that is down).",
        "",
        "## Legend",
        "",
        "| Mark | Meaning |",
        "| --- | --- |",
        f"| {YES} | MowDeck supports it on every mower of the family. A detail after the "
        "colon shows the range or the choices of a representative model. |",
        f"| {VARIES} | Depends on the exact model, the firmware, an add-on module, a link or "
        "the setup in the vendor's app; see the family's notes. |",
        f"| {NOT_OFFERED} | The mower or its vendor's API does not offer it, so MowDeck cannot. |",
        f"| {NOT_YET} | MowDeck does not support it yet for this family. |",
        "",
        f"*{BASIC_COMMANDS}* are part of every connection (ADR 0012); how a mower carries "
        "out an emergency stop differs, see the notes. Safety rules are the same for every "
        "provider: the controller refuses what a mower does not declare before the vendor is "
        "asked.",
        "",
        "## Providers",
        "",
        *_overview(providers),
        "",
    ]
    for provider in providers:
        lines += _provider_section(provider)
    lines += [
        "## Adding to this page",
        "",
        "A provider declares its profiles in `ProviderSpec.capability_profiles` "
        "([Cloud providers: adding a vendor](../dev/cloud-providers.md)); run "
        "`uv run poe capability-matrix` and commit the page. CI fails "
        "(`uv run poe capability-matrix-check`) when the page and the code disagree.",
    ]
    return "\n".join(lines).rstrip() + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else "")
    parser.add_argument("--check", action="store_true", help="exit 1 when the page is stale")
    parser.add_argument("--root", type=Path, default=Path.cwd())
    args = parser.parse_args(argv)
    providers = installed_providers()
    found = problems(providers)
    if found:
        print("\n".join(found), file=sys.stderr)
        return 1
    text = render(providers)
    out: Path = args.root / OUT_FILE
    if args.check:
        if not out.is_file() or out.read_text(encoding="utf-8") != text:
            print(f"{OUT_FILE} is stale: run `uv run poe capability-matrix`", file=sys.stderr)
            return 1
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT_FILE} ({len(providers)} providers)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
