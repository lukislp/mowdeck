#!/usr/bin/env node
// Generates the web app's API types (apps/web/src/lib/generated) from committed sources:
//   1. apps/web/openapi/<service>.json (exported from the services: `uv run poe openapi`)
//      -> <service>.ts with openapi-typescript (paths, components, operations)
//   2. libs/mowdeck-contracts/schemas/v1/Realtime{Server,Client}Message.json
//      -> realtime.ts with json-schema-to-typescript (the WebSocket protocol)
// `--check` writes into a temporary directory and fails when the committed files differ.
// This package has its own TypeScript 5.9 because openapi-typescript 7 declares `typescript ^5`.
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { compile } from 'json-schema-to-typescript';
import openapiTS, { astToString } from 'openapi-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const openapiDir = join(root, 'apps/web/openapi');
const schemaDir = join(root, 'libs/mowdeck-contracts/schemas/v1');
const outDir = join(root, 'apps/web/src/lib/generated');

const BANNER = (source) =>
  `// Generated by tools/ts-codegen from ${source}. Do not edit: run \`pnpm codegen\`.\n` +
  '/* eslint-disable */\n';

async function openapiFiles() {
  const files = {};
  for (const name of readdirSync(openapiDir)
    .filter((f) => f.endsWith('.json'))
    .sort()) {
    const document = JSON.parse(readFileSync(join(openapiDir, name), 'utf8'));
    const ast = await openapiTS(document, { alphabetize: true, exportType: true });
    files[basename(name, '.json') + '.ts'] = BANNER(`apps/web/openapi/${name}`) + astToString(ast);
  }
  return files;
}

async function realtimeFile() {
  const server = JSON.parse(readFileSync(join(schemaDir, 'RealtimeServerMessage.json'), 'utf8'));
  const client = JSON.parse(readFileSync(join(schemaDir, 'RealtimeClientMessage.json'), 'utf8'));
  const strip = ({ $defs: _defs, $schema: _schema, discriminator: _d, ...rest }) => rest;
  const combined = {
    title: 'RealtimeProtocol',
    type: 'object',
    additionalProperties: false,
    properties: {
      server: { $ref: '#/$defs/RealtimeServerMessage' },
      client: { $ref: '#/$defs/RealtimeClientMessage' },
    },
    $defs: {
      ...server.$defs,
      ...client.$defs,
      RealtimeServerMessage: { ...strip(server), title: 'RealtimeServerMessage' },
      RealtimeClientMessage: { ...strip(client), title: 'RealtimeClientMessage' },
    },
  };
  // Pydantic marks fields with defaults as optional; the discriminator is always sent.
  for (const def of Object.values(combined.$defs)) {
    if (def.properties?.type?.const !== undefined) {
      def.required = [...new Set([...(def.required ?? []), 'type'])];
    }
  }
  const ts = await compile(combined, 'RealtimeProtocol', {
    bannerComment: BANNER('libs/mowdeck-contracts/schemas/v1/Realtime*Message.json').trimEnd(),
    additionalProperties: false,
    unreachableDefinitions: true,
    format: false,
    strictIndexSignatures: true,
  });
  return { 'realtime.ts': ts };
}

async function generate(target) {
  mkdirSync(target, { recursive: true });
  const files = { ...(await openapiFiles()), ...(await realtimeFile()) };
  for (const [name, text] of Object.entries(files)) {
    writeFileSync(join(target, name), text.endsWith('\n') ? text : text + '\n');
  }
  return Object.keys(files).sort();
}

const check = process.argv.includes('--check');
if (check) {
  const temp = mkdtempSync(join(tmpdir(), 'mowdeck-codegen-'));
  try {
    const names = await generate(temp);
    const read = (path) => {
      try {
        return readFileSync(path, 'utf8');
      } catch {
        return null;
      }
    };
    const stale = names.filter((name) => read(join(outDir, name)) !== read(join(temp, name)));
    if (stale.length) {
      console.error(`stale generated types: ${stale.join(', ')} (run \`pnpm codegen\`)`);
      process.exit(1);
    }
    console.log(`generated types are up to date (${names.length} files)`);
  } finally {
    rmSync(temp, { recursive: true, force: true });
  }
} else {
  const names = await generate(outDir);
  console.log(`wrote ${names.length} files to apps/web/src/lib/generated`);
}
