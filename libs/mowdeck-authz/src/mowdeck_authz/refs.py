"""Subjects and objects in OpenFGA notation.

An OpenFGA object is ``<type>:<id>`` (``mower:3f2c...``). A subject (the "user" of a tuple) is
an object (``user:<uuid>``, ``api_token:<uuid>``, ``account:<uuid>`` for hierarchy tuples,
``platform:main``) or a userset ``<type>:<id>#<relation>``.

Ids are always generated by the owning service (UUIDs); never build an object from user input
without looking the row up first.
"""

import re
from dataclasses import dataclass
from typing import Self
from uuid import UUID

from mowdeck_contracts.v1 import Principal, PrincipalKind

_NAME = re.compile(r"^[a-z][a-z0-9_]{0,63}$")
_ID = re.compile(r"^[^\s:#]{1,256}$")

USER = "user"
API_TOKEN = "api_token"  # noqa: S105 - type name, not a secret
PLATFORM = "platform"
ACCOUNT = "account"
SITE = "site"
GROUP = "group"
MOWER = "mower"

PLATFORM_ID = "main"
"""There is exactly one platform object, ``platform:main``."""


def _validate(type_: str, id_: str, relation: str | None = None) -> None:
    if not _NAME.match(type_):
        msg = f"invalid type {type_!r}"
        raise ValueError(msg)
    if not _ID.match(id_):
        msg = f"invalid id {id_!r}"
        raise ValueError(msg)
    if relation is not None and not _NAME.match(relation):
        msg = f"invalid relation {relation!r}"
        raise ValueError(msg)


@dataclass(frozen=True, slots=True)
class ObjectRef:
    """An object such as ``mower:<uuid>``; ``str()`` gives the OpenFGA form."""

    type: str
    id: str

    def __post_init__(self) -> None:
        _validate(self.type, self.id)

    def __str__(self) -> str:
        return f"{self.type}:{self.id}"

    @classmethod
    def of(cls, type_: str, id_: UUID | str) -> Self:
        """Build from a type and a UUID (or string id)."""
        return cls(type_, str(id_))

    @classmethod
    def parse(cls, value: str) -> Self:
        """Parse ``<type>:<id>``."""
        type_, sep, id_ = value.partition(":")
        if not sep or "#" in id_:
            msg = f"not an object: {value!r}"
            raise ValueError(msg)
        return cls(type_, id_)

    def as_subject(self, relation: str | None = None) -> "Subject":
        """This object as a subject, optionally as the userset ``<obj>#<relation>``."""
        return Subject(self.type, self.id, relation)


@dataclass(frozen=True, slots=True)
class Subject:
    """A subject such as ``user:<uuid>`` or the userset ``group:<id>#member``."""

    type: str
    id: str
    relation: str | None = None

    def __post_init__(self) -> None:
        _validate(self.type, self.id, self.relation)

    def __str__(self) -> str:
        base = f"{self.type}:{self.id}"
        return f"{base}#{self.relation}" if self.relation else base

    @classmethod
    def parse(cls, value: str) -> Self:
        """Parse ``<type>:<id>`` or ``<type>:<id>#<relation>``."""
        head, _, relation = value.partition("#")
        type_, sep, id_ = head.partition(":")
        if not sep:
            msg = f"not a subject: {value!r}"
            raise ValueError(msg)
        return cls(type_, id_, relation or None)

    def as_object(self) -> ObjectRef:
        """The object part (``user:<id>``) without a userset relation."""
        return ObjectRef(self.type, self.id)


def user(user_id: UUID | str) -> Subject:
    """``user:<id>``: a person or sub-user."""
    return Subject(USER, str(user_id))


def api_token(token_id: UUID | str) -> Subject:
    """``api_token:<id>``: an API token is its own subject with explicit grants."""
    return Subject(API_TOKEN, str(token_id))


def account(account_id: UUID | str) -> ObjectRef:
    """``account:<id>``."""
    return ObjectRef(ACCOUNT, str(account_id))


def site(site_id: UUID | str) -> ObjectRef:
    """``site:<id>``."""
    return ObjectRef(SITE, str(site_id))


def group(group_id: UUID | str) -> ObjectRef:
    """``group:<id>``."""
    return ObjectRef(GROUP, str(group_id))


def mower(mower_id: UUID | str) -> ObjectRef:
    """``mower:<id>``."""
    return ObjectRef(MOWER, str(mower_id))


PLATFORM_OBJECT = ObjectRef(PLATFORM, PLATFORM_ID)
"""``platform:main``: holder of the operator admins."""


def principal_subject(principal: Principal) -> Subject:
    """Map a verified principal to its OpenFGA subject.

    ``USER`` and ``SUBUSER`` become ``user:<subject>``, ``API_TOKEN`` becomes
    ``api_token:<subject>`` (the JWT ``sub`` of an API token is the token id). ``SERVICE``
    principals never hold object rights in the model and raise ``ValueError``: a service acting
    on its own behalf uses dedicated internal routes, not user permissions.
    """
    match principal.kind:
        case PrincipalKind.USER | PrincipalKind.SUBUSER:
            return user(principal.subject)
        case PrincipalKind.API_TOKEN:
            return api_token(principal.subject)
        case _:
            msg = f"principals of kind {principal.kind.value!r} have no object rights"
            raise ValueError(msg)
